-- JAVIRU product catalogue for manually imported supplier products.
-- Run once in Supabase Dashboard -> SQL Editor.
-- Product creation is limited to trusted accounts whose Supabase Auth app_metadata
-- is jamesbishopemmanuel@gmail.com. The API also enforces this exact account email.
create table if not exists public.javiru_products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 180),
  category text not null check (char_length(category) between 1 and 80),
  description text not null default '',
  price numeric(12,2) not null check (price > 0),
  old_price numeric(12,2) not null check (old_price >= price),
  emoji text not null default '📦',
  bg text not null default '#f0f2ec',
  tag text not null default 'IMPORTED',
  rating numeric(2,1) not null default 4.5 check (rating >= 0 and rating <= 5),
  stock integer not null default 0 check (stock >= 0),
  source_url text,
  image_url text,
  supplier_product_id text,
  source_name text not null default 'JAVIRU',
  active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists javiru_products_active_created_idx
  on public.javiru_products (active, created_at desc);

alter table public.javiru_products enable row level security;

drop policy if exists "Anyone can view active JAVIRU products" on public.javiru_products;
create policy "Anyone can view active JAVIRU products"
  on public.javiru_products for select
  to anon, authenticated
  using (active = true);

drop policy if exists "JAVIRU product admins can add products" on public.javiru_products;
create policy "JAVIRU product admins can add products"
  on public.javiru_products for insert
  to authenticated
  with check (
    auth.uid() = created_by
    and lower(coalesce(auth.jwt() ->> 'email', '')) = 'jamesbishopemmanuel@gmail.com'
  );

revoke all on public.javiru_products from anon;
grant select on public.javiru_products to anon, authenticated;
grant insert on public.javiru_products to authenticated;


-- JAVIRU customer orders
CREATE TABLE IF NOT EXISTS public.javiru_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  reference TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT NOT NULL,
  address TEXT NOT NULL,
  state TEXT NOT NULL,
  payment_method TEXT NOT NULL DEFAULT 'Pay on delivery',
  status TEXT NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled')),
  total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
  items JSONB NOT NULL DEFAULT '[]'::jsonb
    CHECK (jsonb_typeof(items) = 'array'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS javiru_orders_user_created_idx
  ON public.javiru_orders (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS javiru_orders_created_idx
  ON public.javiru_orders (created_at DESC);

ALTER TABLE public.javiru_orders ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Customers and JAVIRU admin can view orders"
  ON public.javiru_orders;
CREATE POLICY "Customers and JAVIRU admin can view orders"
  ON public.javiru_orders
  FOR SELECT
  TO authenticated
  USING (
    auth.uid() = user_id
    OR LOWER(COALESCE(auth.jwt() ->> 'email', '')) = 'jamesbishopemmanuel@gmail.com'
  );

DROP POLICY IF EXISTS "Customers can place own orders"
  ON public.javiru_orders;
CREATE POLICY "Customers can place own orders"
  ON public.javiru_orders
  FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "JAVIRU admin can update order status"
  ON public.javiru_orders;
CREATE POLICY "JAVIRU admin can update order status"
  ON public.javiru_orders
  FOR UPDATE
  TO authenticated
  USING (
    LOWER(COALESCE(auth.jwt() ->> 'email', '')) = 'jamesbishopemmanuel@gmail.com'
  )
  WITH CHECK (
    LOWER(COALESCE(auth.jwt() ->> 'email', '')) = 'jamesbishopemmanuel@gmail.com'
  );

REVOKE ALL ON public.javiru_orders FROM anon;
GRANT SELECT, INSERT ON public.javiru_orders TO authenticated;
GRANT UPDATE (status) ON public.javiru_orders TO authenticated;

